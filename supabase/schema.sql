-- LYFESTYL: persistence moved to Apple CloudKit
-- ----------------------------------------------------------------------------
-- This file is OBSOLETE. LYFESTYL no longer uses Supabase or any SQL database.
-- Persistence and auth now run entirely on first-party Apple frameworks:
-- CloudKit (private database) for storage and sync, gated by Sign in with
-- Apple. There is no external service, no SQL schema, no secrets to
-- configure, and no server to run this file against.
--
-- The private CloudKit database is auto-scoped to the signed-in iCloud
-- account, so there is nothing equivalent to Row Level Security to write:
-- every record is already private to its owner by construction.
--
-- The file is kept (not deleted) purely as a historical record of the old
-- schema shape, and to document the CloudKit record type that replaced it.
-- See README.md for the current setup instructions.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- CloudKit record type: Entry
-- ----------------------------------------------------------------------------
-- Container:      iCloud.Moments.LYFESTYLE
-- Database:       Private
-- Record type:    Entry
-- recordName:     the entry's UUID
-- Created by:     CloudKit auto-schema, on first save, Development environment
--
-- Fields:
--   rawText         String              raw typed or transcribed text
--   source          String              "text" or "voice"
--   status          String              "pending" / "processing" / "processed" / "failed"
--   schemaVersion   Int                 currently 6
--   category        String, optional    NUTRITION / ACTIVITY / SLEEP / HEALTH / MIND / SOCIAL
--   subtag          String, optional    refinement of the category (e.g. SOCIAL's relationship, a meal type)
--   title           String, optional    clean, neutral display title
--   entryDate       Date                the day the entry belongs to
--   createdAt       Date                when the record was created
--   userID          String, optional    local tag only; CloudKit already scopes the
--                                       private database to the signed-in iCloud account
--   fields          JSON blob           the user's organized answers
--   workout         JSON blob, optional structured exercises/sets/reps/weight, ACTIVITY only
--
-- No tables, no indexes, no RLS policies, no migrations. CloudKit manages the
-- schema for you; deploy Development to Production from the CloudKit Console
-- when ready to ship.
-- ============================================================================
